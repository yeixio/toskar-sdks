//go:build ignore

// Command codes writes codes.go: Toskar Core's error codes, from its
// English error catalog (spec/errors.json), and the contract the SDK was
// built for, from the spec.
//
//	go run scripts/codes.go
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

func main() {
	var catalog map[string]string
	read("../spec/errors.json", &catalog)
	var spec struct {
		Info struct {
			Version string `json:"version"`
		} `json:"info"`
	}
	read("../spec/openapi.sdk.json", &spec)

	codes := make([]string, 0, len(catalog))
	for code := range catalog {
		codes = append(codes, code)
	}
	sort.Strings(codes)

	var b bytes.Buffer
	b.WriteString("// Code generated by scripts/codes.go from Toskar Core's error catalog. DO NOT EDIT.\n\npackage toskar\n\n")
	fmt.Fprintf(&b, "// ContractVersion is the client contract this SDK was built for.\nconst ContractVersion = %q\n\n", spec.Info.Version)
	b.WriteString("// The codes Toskar Core answers errors with, as APIError.Code. A newer\n// Core may answer with one this list doesn't have yet.\nconst (\n")
	for _, code := range codes {
		text := strings.Join(strings.Fields(catalog[code]), " ")
		fmt.Fprintf(&b, "\t// ErrorCode%s: %s\n\tErrorCode%s = %q\n", camel(code), text, camel(code), code)
	}
	b.WriteString(")\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("codes.go", out, 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("codes.go: %d codes, contract %s\n", len(codes), spec.Info.Version)
}

func read(path string, v any) {
	raw, err := os.ReadFile(path)
	if err != nil {
		panic(err)
	}
	if err := json.Unmarshal(raw, v); err != nil {
		panic(err)
	}
}

// camel turns NO_MODEL_INSTALLED into NoModelInstalled.
func camel(code string) string {
	var b strings.Builder
	for _, part := range strings.Split(strings.ToLower(code), "_") {
		if part != "" {
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return b.String()
}
