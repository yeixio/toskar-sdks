"""Generates the Rust SDK's code from spec/openapi.sdk.json.

- src/generated/models.rs: a struct for each schema, and for each inline
  object, named after where it is (ChatRequest, ModelRatingModel).
- src/generated/api.rs: an async method for each operation, on Api, named
  after its operationId.
- src/generated/codes.rs: the error codes, and the contract the SDK was
  built for.

Standard library only, so the sync workflow runs it without Rust.

    python3 rust/scripts/generate.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT.parent / "spec" / "openapi.sdk.json"
ERRORS = ROOT.parent / "spec" / "errors.json"
OUT = ROOT / "src" / "generated"
METHODS = ("get", "post", "put", "patch", "delete")
HEAD = "// Generated by rust/scripts/generate.py from spec/openapi.sdk.json. Do not edit.\n"

# Rust's reserved words, which a field or argument can only be as r#word.
KEYWORDS = set("""
as async await break const continue crate dyn else enum extern false fn for if impl in let loop match mod move mut pub
ref return self static struct super trait true type unsafe use where while abstract become box do final macro override
priv typeof unsized virtual yield try gen
""".split())


def pascal(name: str) -> str:
    parts = re.split(r"[^0-9a-zA-Z]+", name)
    out = "".join(p[:1].upper() + p[1:] for p in parts if p)
    return "N" + out if out[:1].isdigit() else out


def snake(name: str) -> str:
    name = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    name = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", "_", name)
    name = re.sub(r"[^0-9a-zA-Z]+", "_", name).strip("_").lower()
    if name[:1].isdigit():
        name = "n" + name
    return f"r#{name}" if name in KEYWORDS else name


def ref_name(schema: dict) -> str | None:
    ref = schema.get("$ref", "")
    return ref.rsplit("/", 1)[-1] if ref.startswith("#/components/schemas/") else None


def doc(text: str | None, indent: str) -> str:
    """A doc comment, or nothing. Text in brackets would be read as a link, and
    in angle brackets as HTML, so they're escaped."""
    if not text or not text.strip():
        return ""
    text = text.strip().replace("[", "\\[").replace("]", "\\]").replace("<", "&lt;").replace(">", "&gt;")
    return "".join(f"{indent}///{(' ' + line) if line.strip() else ''}\n" for line in text.split("\n"))


class Models:
    """The spec's schemas as Rust structs, with the inline objects found
    along the way."""

    def __init__(self, spec: dict) -> None:
        self.schemas: dict = spec["components"]["schemas"]
        self.classes: dict[str, str] = {}
        self.pending: list[tuple[str, dict]] = []
        for name, schema in self.schemas.items():
            if self.is_class(schema):
                self.claim(name)
                self.pending.append((name, schema))

    def claim(self, name: str) -> None:
        if name in self.classes:
            sys.exit(f"two schemas would be named {name}")
        self.classes[name] = ""

    @staticmethod
    def props(schema: dict, schemas: dict) -> tuple[dict, set]:
        """A schema's properties and required ones, with allOf merged."""
        props: dict = {}
        required: set = set()
        for part in schema.get("allOf", []):
            part = schemas[ref_name(part)] if ref_name(part) else part
            p, r = Models.props(part, schemas)
            props.update(p)
            required |= r
        props.update(schema.get("properties") or {})
        required |= set(schema.get("required", []))
        return props, required

    def is_class(self, schema: dict) -> bool:
        return bool(self.props(schema, self.schemas)[0])

    def type(self, schema: dict | None, where: str) -> str:
        """The Rust type of a schema, without Option. where names an inline
        object's struct."""
        if not schema:
            return "Value"
        if (name := ref_name(schema)) is not None:
            target = self.schemas[name]
            return name if self.is_class(target) else self.type(target, name)
        if "oneOf" in schema or "anyOf" in schema:
            return "Value"
        if self.is_class(schema):
            self.claim(where)
            self.pending.append((where, schema))
            return where
        kind = schema.get("type")
        if kind == "array":
            item = self.type(schema.get("items"), where + "Item" if where.endswith("Response") else where)
            return f"Vec<{self.optional(item, schema.get('items') or {})}>"
        if kind == "object":
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                return f"BTreeMap<String, {self.optional(self.type(extra, where + 'Value'), extra)}>"
            return "Map<String, Value>"
        if kind == "string":
            return {"date-time": "OffsetDateTime", "binary": "Vec<u8>"}.get(schema.get("format", ""), "String")
        # Core's integers are Go's int and int64: 64 bits.
        return {"integer": "i64", "number": "f64", "boolean": "bool"}.get(kind, "Value")

    @staticmethod
    def optional(kind: str, schema: dict) -> str:
        return f"Option<{kind}>" if schema.get("nullable") else kind

    def write(self) -> str:
        out = []
        while self.pending:
            name, schema = self.pending.pop(0)
            out.append(self.struct(name, schema))
        return (
            HEAD
            + "//! Every schema of Toskar Core's API, as a struct. Fields Core may leave out are\n"
            + "//! `Option`, and every struct is `Default`, so a request names only what it sets:\n"
            + "//! `ChatRequest { message: \"Hi\".into(), ..Default::default() }`.\n\n"
            + "#![allow(clippy::all)]\n\n"
            + "use std::collections::BTreeMap;\n\n"
            + "use serde::{Deserialize, Serialize};\nuse serde_json::{Map, Value};\nuse time::OffsetDateTime;\n\n"
            + "\n".join(out)
        )

    def struct(self, name: str, schema: dict) -> str:
        props, required = self.props(schema, self.schemas)
        lines = []
        defaults = []  # each field's default, for a struct that can't derive one
        for prop, s in props.items():
            kind = self.type(s, name + pascal(prop))
            optional = prop not in required or s.get("nullable") or kind == "Value"
            if (target := ref_name(s)) and self.schemas[target].get("nullable"):
                optional = True
            field = snake(prop)
            attrs = [f'rename = "{prop}"'] if field.removeprefix("r#") != prop else []
            default = "Default::default()"
            if optional and kind != "Value":
                attrs += ["default", 'skip_serializing_if = "Option::is_none"']
                if kind == "OffsetDateTime":
                    attrs.append('with = "time::serde::rfc3339::option"')
                kind = f"Option<{kind}>"
            elif kind == "Value":
                attrs += ["default", 'skip_serializing_if = "Value::is_null"']
            elif kind == "OffsetDateTime":
                attrs.append('with = "time::serde::rfc3339"')
                # A required time has no natural default; the Unix epoch stands in.
                default = "OffsetDateTime::UNIX_EPOCH"
            elif kind.startswith(("Vec<", "BTreeMap<", "Map<")):
                attrs.append("default")
            line = doc(s.get("description"), "    ")
            if attrs:
                line += f"    #[serde({', '.join(attrs)})]\n"
            lines.append(line + f"    pub {field}: {kind},\n")
            defaults.append((field, default))
        derives = all(d == "Default::default()" for _, d in defaults)
        derive = f"#[derive(Debug, Clone, PartialEq, Serialize, Deserialize{', Default' if derives else ''})]\n"
        out = doc(schema.get("description"), "") + derive + f"pub struct {name} {{\n" + "".join(lines) + "}\n"
        if not derives:
            out += (
                f"\nimpl Default for {name} {{\n    fn default() -> Self {{\n        Self {{\n"
                + "".join(f"            {f}: {d},\n" for f, d in defaults)
                + "        }\n    }\n}\n"
            )
        return out


def answer(op: dict, models: Models, name: str) -> str:
    """What an operation answers, as a Rust type: () for nothing."""
    for code, response in sorted(op.get("responses", {}).items()):
        if not str(code).startswith("2"):
            continue
        content = response.get("content") or {}
        if "application/json" in content:
            schema = content["application/json"].get("schema")
            return models.optional(models.type(schema, name + "Response"), schema or {})
        if content:
            return "Vec<u8>"
        return "()"
    return "()"


def qualified(kind: str) -> str:
    """A model type as api.rs writes it: through models::."""
    keep = {"Vec", "BTreeMap", "Map", "String", "Value", "Option", "OffsetDateTime", "i64", "f64", "bool", "u8"}
    return re.sub(r"\b[A-Za-z_]\w*\b", lambda m: m.group(0) if m.group(0) in keep else "models::" + m.group(0), kind)


def operations(spec: dict, models: Models) -> str:
    out = []
    for path, ops in sorted(spec["paths"].items()):
        for method in METHODS:
            op = ops.get(method)
            if not op or "operationId" not in op:
                continue
            responses = op.get("responses", {})
            ok = [r.get("content") or {} for c, r in responses.items() if str(c).startswith("2")]
            if ok and all("text/event-stream" in c and "application/json" not in c for c in ok):
                continue  # the events stream is Client::events()
            name = pascal(op["operationId"])
            params = op.get("parameters", [])
            order = re.findall(r"\{([^}]+)\}", path)
            path_params = sorted((p for p in params if p["in"] == "path"), key=lambda p: order.index(p["name"]))
            headers = [p for p in params if p["in"] == "header"]
            query = [p for p in params if p["in"] == "query"]
            content = (op.get("requestBody") or {}).get("content", {})
            required_body = (op.get("requestBody") or {}).get("required", False)

            args: list[str] = []
            notes: list[str] = []
            for p in path_params + [h for h in headers if h.get("required")]:
                args.append(f"{snake(p['name'])}: &str")
                if p.get("description"):
                    notes.append(f"`{snake(p['name']).removeprefix('r#')}`: {p['description'].strip()}")
            body = "None"
            if "application/json" in content:
                schema = content["application/json"].get("schema")
                kind = qualified(models.type(schema, name + "Request"))
                args.append(f"body: &{kind}" if required_body else f"body: Option<&{kind}>")
                body = "Some(json(body)?)" if required_body else "body.map(json).transpose()?"
            elif content:
                found = next(iter(content))
                raw = models.type(content[found].get("schema"), name + "Request")
                media = "application/octet-stream" if found == "*/*" else found
                kind = "Vec<u8>" if raw == "Vec<u8>" else "String"
                args.append(f"body: {kind}" if required_body else f"body: Option<{kind}>")
                into = f'Some(raw(body, "{media}"))' if required_body else f'body.map(|b| raw(b, "{media}"))'
                body = into
            for p in [h for h in headers if not h.get("required")] + query:
                kind = qualified(models.type(p.get("schema"), name + pascal(p["name"])))
                kind = "&str" if kind == "String" else kind
                args.append(f"{snake(p['name'])}: Option<{kind}>")
                if p.get("description"):
                    notes.append(f"`{snake(p['name']).removeprefix('r#')}`: {p['description'].strip()}")
            result = qualified(answer(op, models, name))
            query_expr = "&[" + ", ".join(f'("{q["name"]}", {snake(q["name"])}.map(|v| v.to_string()))' for q in query) + "]"
            header_expr = "&[" + ", ".join(
                f'("{h["name"]}", Some({snake(h["name"])}.to_string()))' if h.get("required")
                else f'("{h["name"]}", {snake(h["name"])}.map(|v| v.to_string()))' for h in headers) + "]"
            segments = "&[" + ", ".join(snake(p["name"]) for p in path_params) + "]"
            read = "call" if result not in ("()", "Vec<u8>") else ("bytes" if result == "Vec<u8>" else "send")
            text = "\n\n".join(s.strip() for s in (op.get("summary"), op.get("description")) if s) or op["operationId"]
            if notes:
                text += "\n\n" + "\n".join(f"- {n}" for n in notes)
            out.append(
                doc(text, "    ")
                + "    #[allow(clippy::too_many_arguments)]\n"
                + f"    pub async fn {snake(op['operationId'])}(&self, {', '.join(args)}) -> Result<{result}> {{\n"
                + f'        self.client.{read}("{method.upper()}", "{path}", {segments}, {query_expr}, {header_expr}, {body}).await\n'
                + "    }\n"
            )
    return (
        HEAD
        + "use std::collections::BTreeMap;\n\nuse serde_json::{Map, Value};\n\n"
        + "use crate::api::{json, raw, Api};\nuse crate::{models, Result};\n\n"
        + "#[allow(unused_imports)]\nuse time::OffsetDateTime;\n\n"
        + "impl Api<'_> {\n"
        + "\n".join(out)
        + "}\n\n"
        + "#[allow(dead_code)]\nfn _unused(_: BTreeMap<String, Value>, _: Map<String, Value>) {}\n"
    )


def codes(spec: dict) -> str:
    catalog = json.loads(ERRORS.read_text())
    lines = []
    for code in sorted(catalog):
        text = re.sub(r"\s+", " ", str(catalog[code]))
        lines.append(doc(text, "    ") + f'    pub const {code}: &str = "{code}";\n')
    return (
        HEAD
        + "/// The client contract this SDK was built for.\n"
        + f'pub const CONTRACT_VERSION: &str = "{spec["info"]["version"]}";\n\n'
        + "/// The codes Toskar Core answers errors with, for [`crate::Error::code`]. A newer\n"
        + "/// Core may answer with one this list doesn't have yet.\n"
        + "pub mod error_codes {\n"
        + "\n".join(lines)
        + "}\n"
    )


def main() -> None:
    spec = json.loads(SPEC.read_text())
    models = Models(spec)
    api = operations(spec, models)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "api.rs").write_text(api)
    (OUT / "models.rs").write_text(models.write())
    (OUT / "codes.rs").write_text(codes(spec))
    print(f"rust: contract {spec['info']['version']}, {len(models.classes)} structs")


if __name__ == "__main__":
    main()
