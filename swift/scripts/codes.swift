// Writes Sources/Toskar/Codes.swift: Toskar Core's error codes, from its
// English error catalog (spec/errors.json), and the contract the SDK was
// built for, from the spec. Run from swift/:
//
//     swift scripts/codes.swift
import Foundation

func json(_ path: String) -> Any {
    try! JSONSerialization.jsonObject(with: Data(contentsOf: URL(fileURLWithPath: path)))
}

let catalog = json("../spec/errors.json") as! [String: String]
let info = (json("../spec/openapi.sdk.json") as! [String: Any])["info"] as! [String: Any]
let contract = info["version"] as! String

let keywords: Set<String> = ["default", "internal", "private", "public", "return", "self", "static", "switch", "true", "false", "in", "is", "as", "nil"]

func camel(_ code: String) -> String {
    let parts = code.lowercased().split(separator: "_").map(String.init)
    let name = parts.enumerated().map { $0.offset == 0 ? $0.element : $0.element.prefix(1).uppercased() + $0.element.dropFirst() }.joined()
    return keywords.contains(name) ? "`\(name)`" : name
}

var out = """
    // Generated by scripts/codes.swift from Toskar Core's error catalog. DO NOT EDIT.

    /// The client contract this SDK was built for, sent as Toskar-Client-Contract.
    public let contractVersion = "\(contract)"

    /// The codes Toskar Core answers errors with. A newer Core may answer with
    /// one this list doesn't have yet.
    extension ToskarError.Code {

    """
for code in catalog.keys.sorted() {
    let text = catalog[code]!.split(whereSeparator: \.isWhitespace).joined(separator: " ")
    out += "    /// \(text)\n    public static let \(camel(code)) = Self(\"\(code)\")\n"
}
out += "}\n"
try! out.write(toFile: "Sources/Toskar/Codes.swift", atomically: true, encoding: .utf8)
print("Codes.swift: \(catalog.count) codes, contract \(contract)")
