"""Generates the Kotlin SDK's code from spec/openapi.sdk.json.

- src/main/kotlin/ai/toskar/api/Models.kt: a data class for each schema,
  and for each inline object, named after where it is (ChatRequest,
  ModelRatingModel).
- src/main/kotlin/ai/toskar/api/Api.kt: a method for each operation, named
  after its operationId.
- src/main/kotlin/ai/toskar/Codes.kt: the error codes, and the contract the
  SDK was built for.

Standard library only, so the sync workflow runs it without a JDK.

    python3 kotlin/scripts/generate.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT.parent / "spec" / "openapi.sdk.json"
ERRORS = ROOT.parent / "spec" / "errors.json"
OUT = ROOT / "src" / "main" / "kotlin" / "ai" / "toskar"
METHODS = ("get", "post", "put", "patch", "delete")
HEAD = "// Generated by kotlin/scripts/generate.py from spec/openapi.sdk.json. Do not edit.\n"

KEYWORDS = {
    "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is",
    "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof",
    "val", "var", "when", "while",
}


def pascal(name: str) -> str:
    parts = re.split(r"[^0-9a-zA-Z]+", name)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def camel(name: str) -> str:
    p = pascal(name)
    # A leading run of capitals is one word: API_KEY -> apiKey, URL -> url.
    m = re.match(r"^[A-Z0-9]+(?=[A-Z][a-z]|$)", p)
    head = m.group(0) if m else p[:1]
    out = head.lower() + p[len(head):]
    if out[:1].isdigit():
        out = "n" + out
    return f"`{out}`" if out in KEYWORDS else out


def ref_name(schema: dict) -> str | None:
    ref = schema.get("$ref", "")
    return ref.rsplit("/", 1)[-1] if ref.startswith("#/components/schemas/") else None


def kdoc(text: str | None, indent: str) -> str:
    """A KDoc comment, or nothing."""
    if not text or not text.strip():
        return ""
    # Kotlin comments nest, so an opening in the text would swallow the code after it.
    text = text.strip().replace("*/", "*&#47;").replace("/*", "&#47;*")
    lines = text.split("\n")
    if len(lines) == 1:
        return f"{indent}/** {lines[0]} */\n"
    body = "".join(f"{indent} *{(' ' + line) if line.strip() else ''}\n" for line in lines)
    return f"{indent}/**\n{body}{indent} */\n"


class Models:
    """The spec's schemas as Kotlin data classes, with the inline objects
    found along the way."""

    def __init__(self, spec: dict) -> None:
        self.schemas: dict = spec["components"]["schemas"]
        self.classes: dict[str, str] = {}
        self.pending: list[tuple[str, dict]] = []
        for name, schema in self.schemas.items():
            if self.is_class(schema):
                self.claim(name)
                self.pending.append((name, schema))

    def claim(self, name: str) -> None:
        if name in self.classes:
            sys.exit(f"two schemas would be named {name}")
        self.classes[name] = ""

    @staticmethod
    def props(schema: dict, schemas: dict) -> tuple[dict, set]:
        """A schema's properties and required ones, with allOf merged."""
        props: dict = {}
        required: set = set()
        for part in schema.get("allOf", []):
            part = schemas[ref_name(part)] if ref_name(part) else part
            p, r = Models.props(part, schemas)
            props.update(p)
            required |= r
        props.update(schema.get("properties") or {})
        required |= set(schema.get("required", []))
        return props, required

    def is_class(self, schema: dict) -> bool:
        return bool(self.props(schema, self.schemas)[0])

    def type(self, schema: dict | None, where: str) -> str:
        """The Kotlin type of a schema, without nullability. where names an
        inline object's class."""
        if not schema:
            return "JsonElement"
        if (name := ref_name(schema)) is not None:
            target = self.schemas[name]
            return name if self.is_class(target) else self.type(target, name)
        if "oneOf" in schema or "anyOf" in schema:
            return "JsonElement"
        if self.is_class(schema):
            self.claim(where)
            self.pending.append((where, schema))
            return where
        kind = schema.get("type")
        if kind == "array":
            item = self.type(schema.get("items"), where + "Item" if where.endswith("Response") else where)
            return f"List<{self.nullable(item, schema.get('items') or {})}>"
        if kind == "object":
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                return f"Map<String, {self.nullable(self.type(extra, where + 'Value'), extra)}>"
            return "JsonObject"
        if kind == "string":
            return {"date-time": "Instant", "binary": "ByteArray"}.get(schema.get("format", ""), "String")
        # Core's integers are Go's int and int64: 64 bits.
        return {"integer": "Long", "number": "Double", "boolean": "Boolean"}.get(kind, "JsonElement")

    @staticmethod
    def nullable(kind: str, schema: dict) -> str:
        return kind + "?" if schema.get("nullable") or kind == "JsonElement" else kind

    def write(self) -> str:
        out = []
        while self.pending:
            name, schema = self.pending.pop(0)
            out.append(self.data_class(name, schema))
        return (
            HEAD
            + "@file:UseSerializers(CoreInstant::class)\n\n"
            + "package ai.toskar.api\n\n"
            + "import ai.toskar.CoreInstant\n"
            + "import java.time.Instant\n"
            + "import kotlinx.serialization.SerialName\n"
            + "import kotlinx.serialization.Serializable\n"
            + "import kotlinx.serialization.UseSerializers\n"
            + "import kotlinx.serialization.json.JsonElement\n"
            + "import kotlinx.serialization.json.JsonObject\n\n"
            + "\n".join(out)
        )

    def data_class(self, name: str, schema: dict) -> str:
        props, required = self.props(schema, self.schemas)
        fields = []
        for prop, s in props.items():
            kind = self.type(s, name + pascal(prop))
            optional = prop not in required or s.get("nullable") or kind == "JsonElement"
            if (target := ref_name(s)) and self.schemas[target].get("nullable"):
                optional = True
            fields.append((prop, s, kind, bool(optional)))
        # Required first, so Java's overloads can leave out the optional ones.
        fields.sort(key=lambda f: f[3])
        lines = []
        for prop, s, kind, optional in fields:
            desc = s.get("description")
            if not desc and (target := ref_name(s)):
                desc = None
            lines.append(kdoc(desc, "    ") + f'    @SerialName({json.dumps(prop)}) public val {camel(prop)}: '
                         + (f"{kind}? = null" if optional else kind) + ",\n")
        doc = kdoc(schema.get("description"), "")
        return doc + f"@Serializable\npublic data class {name} @JvmOverloads constructor(\n" + "".join(lines) + ")\n"


def answer(op: dict, models: Models, name: str) -> str:
    """What an operation answers, as a Kotlin type: Unit for nothing."""
    for code, response in sorted(op.get("responses", {}).items()):
        if not str(code).startswith("2"):
            continue
        content = response.get("content") or {}
        if "application/json" in content:
            schema = content["application/json"].get("schema")
            return models.nullable(models.type(schema, name + "Response"), schema or {})
        if content:
            return "ByteArray"
        return "Unit"
    return "Unit"


def doc(op: dict, params: list[tuple[str, str | None]]) -> str:
    text = "\n\n".join(s.strip() for s in (op.get("summary"), op.get("description")) if s) or op["operationId"]
    tags = [f"@param {p} {d.strip()}" for p, d in params if d and d.strip()]
    return kdoc(text + ("\n\n" + "\n".join(tags) if tags else ""), "    ")


def operations(spec: dict, models: Models) -> str:
    out = []
    for path, ops in sorted(spec["paths"].items()):
        for method in METHODS:
            op = ops.get(method)
            if not op or "operationId" not in op:
                continue
            responses = op.get("responses", {})
            ok = [r.get("content") or {} for c, r in responses.items() if str(c).startswith("2")]
            if ok and all("text/event-stream" in c and "application/json" not in c for c in ok):
                continue  # the events stream is Toskar.events()
            name = pascal(op["operationId"])
            params = op.get("parameters", [])
            order = re.findall(r"\{([^}]+)\}", path)
            path_params = sorted((p for p in params if p["in"] == "path"), key=lambda p: order.index(p["name"]))
            headers = [p for p in params if p["in"] == "header"]
            query = [p for p in params if p["in"] == "query"]
            content = (op.get("requestBody") or {}).get("content", {})
            required_body = (op.get("requestBody") or {}).get("required", False)

            args: list[str] = []
            docs: list[tuple[str, str | None]] = []
            for p in path_params + [h for h in headers if h.get("required")]:
                args.append(f"{camel(p['name'])}: {models.type(p.get('schema'), name + pascal(p['name']))}")
                docs.append((camel(p["name"]), p.get("description")))
            body = "null"
            if "application/json" in content:
                schema = content["application/json"].get("schema")
                kind = models.nullable(models.type(schema, name + "Request"), schema or {})
                args.append(f"body: {kind}" if required_body else f"body: {kind.rstrip('?')}? = null")
                body = "toskar.json(body)"
            elif content:
                media = next(iter(content))
                kind = models.type(content[media].get("schema"), name + "Request")
                media = "application/octet-stream" if media == "*/*" else media
                args.append(f"body: {kind}" if required_body else f"body: {kind}? = null")
                body = f"toskar.raw(body, {json.dumps(media)})"
            for p in [h for h in headers if not h.get("required")] + query:
                args.append(f"{camel(p['name'])}: {models.type(p.get('schema'), name + pascal(p['name']))}? = null")
                docs.append((camel(p["name"]), p.get("description")))
            result = answer(op, models, name)

            names = [camel(p["name"]) for p in path_params]
            call = [
                json.dumps(method.upper()),
                json.dumps(path),
                f"listOf({', '.join(names)})",
            ]
            if query:
                call.append("query = listOf(" + ", ".join(f"{json.dumps(q['name'])} to {camel(q['name'])}" for q in query) + ")")
            if headers:
                call.append("headers = listOf(" + ", ".join(f"{json.dumps(h['name'])} to {camel(h['name'])}" for h in headers) + ")")
            if body != "null":
                call.append(f"body = {body}")
            overloads = "    @JvmOverloads\n" if any("=" in a for a in args) else ""
            out.append(
                doc(op, docs)
                + overloads
                + f"    public fun {camel(op['operationId'])}({', '.join(args)}): {result} =\n"
                + f"        toskar.call({', '.join(call)})\n"
            )
    return (
        HEAD
        + "package ai.toskar.api\n\n"
        + "import ai.toskar.Toskar\n"
        + "import kotlinx.serialization.json.JsonElement\n"
        + "import kotlinx.serialization.json.JsonObject\n\n"
        + "/**\n * Every route of Toskar Core's API, typed: `toskar.api.listModels()` and so\n"
        + " * on. Each method waits for its answer, so call it off the main thread.\n"
        + " * An error answer throws a [ai.toskar.ToskarException].\n */\n"
        + "public class Api internal constructor(private val toskar: Toskar) {\n"
        + "\n".join(out)
        + "}\n"
    )


def codes(spec: dict) -> str:
    catalog = json.loads(ERRORS.read_text())
    lines = []
    for code in sorted(catalog):
        text = re.sub(r"\s+", " ", str(catalog[code]))
        lines.append(kdoc(text, "    ") + f'    public const val {code}: String = "{code}"\n')
    return (
        HEAD
        + '@file:JvmName("Contract")\n\n'
        + "package ai.toskar\n\n"
        + "/** The client contract this SDK was built for. */\n"
        + f'public const val CONTRACT_VERSION: String = "{spec["info"]["version"]}"\n\n'
        + "/**\n * The codes Toskar Core answers errors with, for [ToskarException.code]. A\n"
        + " * newer Core may answer with one this list doesn't have yet.\n */\n"
        + "public object ErrorCodes {\n"
        + "\n".join(lines)
        + "}\n"
    )


def main() -> None:
    spec = json.loads(SPEC.read_text())
    models = Models(spec)
    api = operations(spec, models)
    (OUT / "api").mkdir(parents=True, exist_ok=True)
    (OUT / "api" / "Api.kt").write_text(api)
    (OUT / "api" / "Models.kt").write_text(models.write())
    (OUT / "Codes.kt").write_text(codes(spec))
    print(f"kotlin: contract {spec['info']['version']}, {len(models.classes)} classes")


if __name__ == "__main__":
    main()
