// Writes src/generated/codes.ts, every error code Toskar Core has, from its
// English error catalog (spec/errors.json) with the message as its doc, and
// src/generated/contract.ts, the contract version the SDK was built for.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const catalog = JSON.parse(readFileSync(join(here, '..', '..', 'spec', 'errors.json'), 'utf8'))
const lines = Object.keys(catalog)
  .sort()
  .map((code) => {
    const text = String(catalog[code]).replaceAll('*/', '* /').replace(/\s+/g, ' ')
    return `  /** ${text} */\n  ${code}: '${code}',`
  })
const out = `// Generated by scripts/codes.mjs from Toskar Core's error catalog. Do not edit.

/**
 * The stable error codes Toskar Core answers with. A newer Core may answer
 * with a code this list doesn't have yet.
 */
export const ErrorCodes = {
${lines.join('\n')}
} as const

/** One of ErrorCodes, or a code from a newer Core. */
export type ErrorCode = (typeof ErrorCodes)[keyof typeof ErrorCodes] | (string & {})
`
writeFileSync(join(here, '..', 'src', 'generated', 'codes.ts'), out)
console.log(`src/generated/codes.ts: ${Object.keys(catalog).length} codes`)

// The client contract the SDK was built for: the spec's info.version.
const spec = JSON.parse(readFileSync(join(here, '..', '..', 'spec', 'openapi.sdk.json'), 'utf8'))
writeFileSync(
  join(here, '..', 'src', 'generated', 'contract.ts'),
  `// Generated by scripts/codes.mjs from the spec. Do not edit.\n\n/** The client contract this SDK was built for. */\nexport const CONTRACT_VERSION = '${spec.info.version}'\n`,
)
console.log(`src/generated/contract.ts: ${spec.info.version}`)
