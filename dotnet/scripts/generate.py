"""Generates the .NET SDK's code from spec/openapi.sdk.json.

- src/Toskar/Generated/Models.cs: a record for each schema, and for each
  inline object, named after where it is (ChatRequest, ModelRatingModel),
  in Toskar.Models.
- src/Toskar/Generated/ToskarApi.cs: an async method for each operation,
  named after its operationId.
- src/Toskar/Generated/Codes.cs: the error codes, and the contract the SDK
  was built for.

Standard library only, so the sync workflow runs it without .NET.

    python3 dotnet/scripts/generate.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT.parent / "spec" / "openapi.sdk.json"
ERRORS = ROOT.parent / "spec" / "errors.json"
OUT = ROOT / "src" / "Toskar" / "Generated"
METHODS = ("get", "post", "put", "patch", "delete")
# The spec doesn't describe every field; the hand-written code is held to
# documenting everything public.
HEAD = (
    "// Generated by dotnet/scripts/generate.py from spec/openapi.sdk.json. Do not edit.\n"
    "#nullable enable\n#pragma warning disable CS1591\n"
)

# Schemas whose names would hide a type that every project imports (C#'s
# implicit usings), so a user's own `Task` would stop compiling.
RENAMES = {"Task": "ToskarTask"}
TAKEN = {
    "Task", "Thread", "Timer", "Action", "Func", "Exception", "Type", "Path", "File", "Directory", "Stream",
    "Environment", "Random", "Math", "Monitor", "Attribute", "Delegate", "Enum", "Object", "String", "Console",
    "Convert", "Buffer", "Array", "Tuple", "Lazy", "Progress", "Parallel", "HttpClient", "HttpMethod", "Uri",
}


def pascal(name: str) -> str:
    parts = re.split(r"[^0-9a-zA-Z]+", name)
    out = "".join(p[:1].upper() + p[1:] for p in parts if p)
    return "N" + out if out[:1].isdigit() else out


def class_name(name: str) -> str:
    name = RENAMES.get(name, name)
    if name in TAKEN:
        sys.exit(f"the schema {name} would hide .NET's {name}: add it to RENAMES in {Path(__file__).name}")
    return name


def ref_name(schema: dict) -> str | None:
    ref = schema.get("$ref", "")
    return ref.rsplit("/", 1)[-1] if ref.startswith("#/components/schemas/") else None


def xml(text: str | None, indent: str) -> str:
    """An XML doc comment's summary, or nothing."""
    if not text or not text.strip():
        return ""
    text = text.strip().replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    lines = text.split("\n")
    return f"{indent}/// <summary>\n" + "".join(f"{indent}/// {line}".rstrip() + "\n" for line in lines) + f"{indent}/// </summary>\n"


class Models:
    """The spec's schemas as C# records, with the inline objects found along
    the way."""

    def __init__(self, spec: dict) -> None:
        self.schemas: dict = spec["components"]["schemas"]
        self.classes: dict[str, str] = {}
        self.pending: list[tuple[str, dict]] = []
        for name, schema in self.schemas.items():
            if self.is_class(schema):
                self.claim(class_name(name))
                self.pending.append((class_name(name), schema))

    def claim(self, name: str) -> None:
        if name in self.classes:
            sys.exit(f"two schemas would be named {name}")
        self.classes[name] = ""

    @staticmethod
    def props(schema: dict, schemas: dict) -> tuple[dict, set]:
        """A schema's properties and required ones, with allOf merged."""
        props: dict = {}
        required: set = set()
        for part in schema.get("allOf", []):
            part = schemas[ref_name(part)] if ref_name(part) else part
            p, r = Models.props(part, schemas)
            props.update(p)
            required |= r
        props.update(schema.get("properties") or {})
        required |= set(schema.get("required", []))
        return props, required

    def is_class(self, schema: dict) -> bool:
        return bool(self.props(schema, self.schemas)[0])

    def type(self, schema: dict | None, where: str) -> str:
        """The C# type of a schema, without nullability. where names an
        inline object's class."""
        if not schema:
            return "JsonNode"
        if (name := ref_name(schema)) is not None:
            target = self.schemas[name]
            return class_name(name) if self.is_class(target) else self.type(target, class_name(name))
        if "oneOf" in schema or "anyOf" in schema:
            return "JsonNode"
        if self.is_class(schema):
            self.claim(where)
            self.pending.append((where, schema))
            return where
        kind = schema.get("type")
        if kind == "array":
            item = self.type(schema.get("items"), where + "Item" if where.endswith("Response") else where)
            return f"List<{self.nullable(item, schema.get('items') or {})}>"
        if kind == "object":
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                return f"Dictionary<string, {self.nullable(self.type(extra, where + 'Value'), extra)}>"
            return "JsonObject"
        if kind == "string":
            return {"date-time": "DateTimeOffset", "binary": "byte[]"}.get(schema.get("format", ""), "string")
        # Core's integers are Go's int and int64: 64 bits.
        return {"integer": "long", "number": "double", "boolean": "bool"}.get(kind, "JsonNode")

    @staticmethod
    def nullable(kind: str, schema: dict) -> str:
        return kind + "?" if schema.get("nullable") or kind == "JsonNode" else kind

    def write(self) -> str:
        out = []
        while self.pending:
            name, schema = self.pending.pop(0)
            out.append(self.record(name, schema))
        return (
            HEAD
            + "using System;\nusing System.Collections.Generic;\nusing System.Text.Json.Nodes;\n"
            + "using System.Text.Json.Serialization;\n\n"
            + "namespace Toskar.Models;\n\n"
            + "\n".join(out)
        )

    def record(self, name: str, schema: dict) -> str:
        props, required = self.props(schema, self.schemas)
        lines = []
        for prop, s in props.items():
            kind = self.type(s, name + pascal(prop))
            member = pascal(prop)
            if member == name:
                # C# doesn't let a member share its type's name.
                member += "Value"
            optional = prop not in required or s.get("nullable") or kind == "JsonNode"
            if (target := ref_name(s)) and self.schemas[target].get("nullable"):
                optional = True
            decl = f"public {kind}? {member} {{ get; init; }}" if optional else f"public required {kind} {member} {{ get; init; }}"
            lines.append(xml(s.get("description"), "    ") + f"    [JsonPropertyName({json.dumps(prop)})]\n    {decl}\n")
        return xml(schema.get("description"), "") + f"public sealed record {name}\n{{\n" + "\n".join(lines) + "}\n"


def answer(op: dict, models: Models, name: str) -> str:
    """What an operation answers, as a C# type: empty for nothing."""
    for code, response in sorted(op.get("responses", {}).items()):
        if not str(code).startswith("2"):
            continue
        content = response.get("content") or {}
        if "application/json" in content:
            schema = content["application/json"].get("schema")
            return models.nullable(models.type(schema, name + "Response"), schema or {})
        if content:
            return "byte[]"
        return ""
    return ""


def qualified(kind: str) -> str:
    """A model type as Api.cs writes it: through the M alias, so a model's
    name never meets one of the System types the file uses."""
    def one(m: re.Match) -> str:
        word = m.group(0)
        if word in ("List", "Dictionary", "string", "long", "double", "bool", "byte", "DateTimeOffset", "JsonNode", "JsonObject"):
            return word
        return "M." + word
    return re.sub(r"\b[A-Za-z_]\w*\b", one, kind)


def doc(op: dict, params: list[tuple[str, str | None]]) -> str:
    text = "\n\n".join(s.strip() for s in (op.get("summary"), op.get("description")) if s) or op["operationId"]
    out = xml(text, "    ")
    # Every parameter, or none: C# warns about a method that documents some.
    for p, d in params:
        text = (d or "").strip() or FALLBACK.get(p, f"The {p}.")
        out += f"    /// <param name=\"{p}\">{text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')}</param>\n"
    return out


FALLBACK = {"body": "The request.", "cancellationToken": "Cancels the request.", "id": "The id."}


def camel(name: str) -> str:
    p = pascal(name)
    m = re.match(r"^[A-Z0-9]+(?=[A-Z][a-z]|$)", p)
    head = m.group(0) if m else p[:1]
    out = head.lower() + p[len(head):]
    return "@" + out if out in KEYWORDS else out


# C#'s reserved words, which a parameter can only be with an @.
KEYWORDS = set("""
abstract as base bool break byte case catch char checked class const continue decimal default delegate do double else
enum event explicit extern false finally fixed float for foreach goto if implicit in int interface internal is lock long
namespace new null object operator out override params private protected public readonly ref return sbyte sealed short
sizeof stackalloc static string struct switch this throw true try typeof uint ulong unchecked unsafe ushort using virtual
void volatile while
""".split())


def operations(spec: dict, models: Models) -> str:
    out = []
    for path, ops in sorted(spec["paths"].items()):
        for method in METHODS:
            op = ops.get(method)
            if not op or "operationId" not in op:
                continue
            responses = op.get("responses", {})
            ok = [r.get("content") or {} for c, r in responses.items() if str(c).startswith("2")]
            if ok and all("text/event-stream" in c and "application/json" not in c for c in ok):
                continue  # the events stream is ToskarClient.EventsAsync()
            name = pascal(op["operationId"])
            params = op.get("parameters", [])
            order = re.findall(r"\{([^}]+)\}", path)
            path_params = sorted((p for p in params if p["in"] == "path"), key=lambda p: order.index(p["name"]))
            headers = [p for p in params if p["in"] == "header"]
            query = [p for p in params if p["in"] == "query"]
            content = (op.get("requestBody") or {}).get("content", {})
            required_body = (op.get("requestBody") or {}).get("required", False)

            args: list[str] = []
            docs: list[tuple[str, str | None]] = []
            for p in path_params + [h for h in headers if h.get("required")]:
                args.append(f"{qualified(models.type(p.get('schema'), name + pascal(p['name'])))} {camel(p['name'])}")
                docs.append((camel(p["name"]).lstrip("@"), p.get("description")))
            body = "null"
            if content:
                docs.append(("body", None))
            if "application/json" in content:
                schema = content["application/json"].get("schema")
                kind = qualified(models.type(schema, name + "Request"))
                args.append(f"{kind} body" if required_body else f"{kind}? body = null")
                body = "Json(body)"
            elif content:
                media = next(iter(content))
                kind = qualified(models.type(content[media].get("schema"), name + "Request"))
                media = "application/octet-stream" if media == "*/*" else media
                args.append(f"{kind} body" if required_body else f"{kind}? body = null")
                body = f"Raw(body, {json.dumps(media)})"
            for p in [h for h in headers if not h.get("required")] + query:
                kind = qualified(models.type(p.get("schema"), name + pascal(p["name"])))
                args.append(f"{kind}? {camel(p['name'])} = null")
                docs.append((camel(p["name"]).lstrip("@"), p.get("description")))
            args.append("CancellationToken cancellationToken = default")
            docs.append(("cancellationToken", None))
            result = qualified(answer(op, models, name))
            task = f"System.Threading.Tasks.Task<{result}>" if result else "Task"

            names = [camel(p["name"]) for p in path_params]
            call = [json.dumps(method.upper()), json.dumps(path), "new[] { " + ", ".join(names) + " }" if names else "NoParams"]
            call.append("new (string, object?)[] { " + ", ".join(f"({json.dumps(q['name'])}, {camel(q['name'])})" for q in query) + " }" if query else "NoPairs")
            call.append("new (string, object?)[] { " + ", ".join(f"({json.dumps(h['name'])}, {camel(h['name'])})" for h in headers) + " }" if headers else "NoPairs")
            call.append(body)
            call.append("cancellationToken")
            target = f"CallAsync<{result}>" if result and result != "byte[]" else ("BytesAsync" if result == "byte[]" else "SendAsync")
            out.append(
                doc(op, docs)
                + f"    public {task} {name}Async({', '.join(args)}) =>\n"
                + f"        client.{target}({', '.join(call)});\n"
            )
    return (
        HEAD
        + "using System.Collections.Generic;\nusing System.Text.Json.Nodes;\nusing System.Threading;\n"
        + "using Task = System.Threading.Tasks.Task;\nusing M = Toskar.Models;\n\n"
        + "namespace Toskar;\n\n"
        + "/// <summary>\n/// Every route of Toskar Core's API, typed: <c>toskar.Api.ListModelsAsync()</c> and so on.\n"
        + "/// An error answer throws a <see cref=\"ToskarException\"/>.\n/// </summary>\n"
        + "public sealed partial class ToskarApi\n{\n"
        + "\n".join(out)
        + "}\n"
    )


def codes(spec: dict) -> str:
    catalog = json.loads(ERRORS.read_text())
    lines = []
    for code in sorted(catalog):
        text = re.sub(r"\s+", " ", str(catalog[code]))
        lines.append(xml(text, "    ") + f'    public const string {code} = "{code}";\n')
    return (
        HEAD
        + "namespace Toskar;\n\n"
        + "/// <summary>The client contract this SDK was built for.</summary>\n"
        + "public static class Contract\n{\n"
        + f'    /// <summary>The contract version, such as {spec["info"]["version"]}.</summary>\n'
        + f'    public const string Version = "{spec["info"]["version"]}";\n'
        + "}\n\n"
        + "/// <summary>\n/// The codes Toskar Core answers errors with, for <see cref=\"ToskarException.Code\"/>. A\n"
        + "/// newer Core may answer with one this list doesn't have yet.\n/// </summary>\n"
        + "public static class ErrorCodes\n{\n"
        + "\n".join(lines)
        + "}\n"
    )


def main() -> None:
    spec = json.loads(SPEC.read_text())
    models = Models(spec)
    api = operations(spec, models)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "ToskarApi.cs").write_text(api)
    (OUT / "Models.cs").write_text(models.write())
    (OUT / "Codes.cs").write_text(codes(spec))
    print(f"dotnet: contract {spec['info']['version']}, {len(models.classes)} records")


if __name__ == "__main__":
    main()
